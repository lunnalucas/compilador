/* Traduce cada carácter a la columna definida en la especificación léxica. */
int get_evento(int c) {
    if (c == EOF) return 21;
    if ((c >= 'a' && c <= 'z') || (c >= 'A' && c <= 'Z')) return 0;
    if (c >= '0' && c <= '9') return 1;
    switch (c) {
        case '=': return 2;
        case '!': return 3;
        case '<': return 4;
        case '>': return 5;
        case '&': return 6;
        case '|': return 7;
        case '+': return 8;
        case '-': return 9;
        case '*': return 10;
        case '/': return 11;
        case '(': return 12;
        case ')': return 13;
        case '{': return 14;
        case '}': return 15;
        case ';': return 16;
        case ',': return 17;
        case '.': return 18;
        case '"': return 19;
        case ' ':
        case '\t':
        case '\n':
        case '\r': return 20;
        default: return -1;
    }
}

